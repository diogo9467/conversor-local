"""Generate native/installer declarations from the shared conversion catalog."""
from pathlib import Path
import hashlib
import json
import re
import uuid
import xml.etree.ElementTree as ET

ROOT=Path(__file__).resolve().parents[1]
DEST=ROOT/'.build/generated'

def generate():
    catalog=json.loads((ROOT/'formats.json').read_text(encoding='utf-8'))
    targets=catalog['targets']; ids=[t['id'] for t in targets]
    assert catalog['schema']==1 and len(ids)==len(set(ids)) and 0<len(ids)<=32
    assert all(re.fullmatch('[a-z0-9]+',i) for i in ids)
    for ext,source in catalog['sources'].items():
        assert re.fullmatch('[a-z0-9]+',ext) and source['targets']
        assert len(source['targets'])==len(set(source['targets']))
        assert set(source['targets'])<=set(ids) and ext not in source['targets']
    identity=catalog['shell']; clsid=str(uuid.UUID(identity['clsid'])).upper()
    assert re.fullmatch(r'Conversor\.Shell\.[a-z0-9]+\.dll',identity['dll'])
    DEST.mkdir(parents=True,exist_ok=True)
    key=uuid.UUID(clsid); data1,data2,data3,*_=key.fields
    guid=f'{{0x{data1:08x},0x{data2:04x},0x{data3:04x},{{'+','.join(f'0x{x:02x}' for x in key.bytes[8:])+'}}'
    lines=['// Generated by tools/catalog.py. Edit formats.json instead.','#pragma once',f'static const CLSID CLSID_Conversor = {guid};',
           'struct ConversionTarget { const char* id; const wchar_t* title; };','static const ConversionTarget ConversionTargets[] = {']
    for t in targets:lines.append('    {'+json.dumps(t['id'])+',L'+json.dumps(t['label'],ensure_ascii=False)+'},')
    lines+=['};',f'static constexpr unsigned long TargetCount = {len(ids)};',
            'struct ConversionSource { const wchar_t* extension; unsigned int mask; };','static const ConversionSource ConversionSources[] = {']
    for ext,source in catalog['sources'].items():
        mask=sum(1<<ids.index(t) for t in source['targets'])
        lines.append(f'    {{L".{ext}",0x{mask:08x}u}},')
    lines+=['};']
    (DEST/'FormatCatalog.h').write_text('\n'.join(lines)+'\n',encoding='utf-8')
    # Inno Setup requires a doubled opening brace in literal GUID strings.
    guid_iss='{{'+clsid+'}'
    registry=[f'Root: HKCU; Subkey: "Software\\Classes\\CLSID\\{guid_iss}"; ValueType: string; ValueName: ""; ValueData: "Conversor Local"; Flags: uninsdeletekey; Tasks: contextmenu',
        f'Root: HKCU; Subkey: "Software\\Classes\\CLSID\\{guid_iss}\\InprocServer32"; ValueType: string; ValueName: ""; ValueData: "{{app}}\\{identity["dll"]}"; Tasks: contextmenu',
        f'Root: HKCU; Subkey: "Software\\Classes\\CLSID\\{guid_iss}\\InprocServer32"; ValueType: string; ValueName: "ThreadingModel"; ValueData: "Apartment"; Tasks: contextmenu']
    for ext in catalog['sources']:
        registry.append(f'Root: HKCU; Subkey: "Software\\Classes\\SystemFileAssociations\\.{ext}\\shell\\ConversorLocal"; Flags: deletekey')
    registry.append('Root: HKCU; Subkey: "Software\\Classes\\*\\shell\\ConversorLocal"; Flags: deletekey')
    handler='Software\\Classes\\*\\shellex\\ContextMenuHandlers\\ConversorLocal'
    registry.extend([f'Root: HKCU; Subkey: "{handler}"; ValueType: string; ValueName: ""; ValueData: "{guid_iss}"; Flags: uninsdeletekey; Tasks: contextmenu',
        f'Root: HKCU; Subkey: "{handler}"; Flags: deletekey; Tasks: not contextmenu',
        f'Root: HKCU; Subkey: "Software\\Classes\\CLSID\\{guid_iss}"; Flags: deletekey; Tasks: not contextmenu'])
    (DEST/'FormatRegistry.iss').write_text('\n'.join(registry)+'\n',encoding='utf-8')
    payload=ROOT/'.build/app'/identity['dll']
    checksum=hashlib.sha256(payload.read_bytes()).hexdigest() if payload.is_file() else ''
    (DEST/'ShellPayload.iss').write_text(f'#define ShellDll "{identity["dll"]}"\n#define ShellBinarySHA256 "{checksum}"\n',encoding='utf-8')
    namespaces={'':'http://schemas.microsoft.com/appx/manifest/foundation/windows10','uap':'http://schemas.microsoft.com/appx/manifest/uap/windows10','uap10':'http://schemas.microsoft.com/appx/manifest/uap/windows10/10',
        'desktop4':'http://schemas.microsoft.com/appx/manifest/desktop/windows10/4','desktop5':'http://schemas.microsoft.com/appx/manifest/desktop/windows10/5','com':'http://schemas.microsoft.com/appx/manifest/com/windows10','rescap':'http://schemas.microsoft.com/appx/manifest/foundation/windows10/restrictedcapabilities'}
    for prefix,uri in namespaces.items():ET.register_namespace(prefix,uri)
    tree=ET.parse(ROOT/'installer/modern/AppxManifest.xml'); package=tree.getroot()
    package.find('{'+namespaces['']+'}Identity').set('Version',(ROOT/'VERSION').read_text().strip()+'.0')
    entry=package.find('.//{'+namespaces['com']+'}Class'); entry.set('Id',clsid);entry.set('Path',identity['dll'])
    context=package.find('.//{'+namespaces['desktop4']+'}FileExplorerContextMenus');context.clear()
    for ext in catalog['sources']:
        node=ET.SubElement(context,'{'+namespaces['desktop5']+'}ItemType',Type='.'+ext)
        ET.SubElement(node,'{'+namespaces['desktop5']+'}Verb',Id='Conversor'+ext.upper(),Clsid=clsid)
    ET.indent(tree,space=' ');tree.write(DEST/'AppxManifest.xml',encoding='utf-8',xml_declaration=True)
    return catalog

if __name__=='__main__':
    c=generate();print(f'Catalog: {len(c["sources"])} source extensions, {len(c["targets"])} output formats.')
